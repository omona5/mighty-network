const assert = require('node:assert/strict');
const RoomManager = require('../src/RoomManager');
const Tutorial = require('../src/Tutorial');
const Rules = require('../src/game/RuleEngine');

function session() {
  const rooms = new RoomManager();
  const packets = [];
  const tutorial = new Tutorial(rooms, (ws, type, data) => packets.push({ type, data: structuredClone(data) }));
  const ws = { clientId: 'learner' };
  const room = tutorial.start(ws);
  const action = (type, data) => tutorial.handle(ws, type, data);
  const step = name => assert.equal(room.tutorial.step, name);
  const ack = () => action('tutorial_ack', { revision: room.tutorial.revision });
  const next = name => { ack(); step(name); };
  const play = cardId => action('play_card', { cardId });
  const state = () => rooms.publicState(room, ws.clientId);
  const deal = () => room.players.flatMap(p => p.hand).concat(room.kitty).map(c => c.id);
  const unchanged = fn => {
    const before = JSON.stringify({ hands: room.players.map(p => p.hand), table: room.tableCards, history: room.trickHistory, step: room.tutorial.step });
    fn();
    assert.equal(JSON.stringify({ hands: room.players.map(p => p.hand), table: room.tableCards, history: room.trickHistory, step: room.tutorial.step }), before);
  };
  assert.equal(deal().length, 53);
  assert.equal(new Set(deal()).size, 53);
  assert.ok(room.players.every(p => p.hand.length === 10));
  assert.ok(room.players[0].hand.every(c => c.suit !== 'DIAMOND'));
  assert.ok(room.players[1].hand.every(c => c.suit !== 'DIAMOND'));
  const firstDeal = deal();
  step('intro');
  unchanged(() => { play('S_A'); action('tutorial_ack', { revision: -1 }); });
  unchanged(() => tutorial.handle({ roomId: ws.roomId, clientId: 'outsider' }, 'tutorial_restart'));
  next('follow');
  assert.equal(room.tableCards.length, 3);
  assert.equal(state().tableWinningCardId, 'C_A');
  ack();
  unchanged(() => action('tutorial_card_hint', { cardId: 'S_A' }));
  assert.match(packets.filter(p => p.type === 'tutorial_feedback').at(-1).data.message, /마이티는 무늬를 따르지 않아도/);
  unchanged(() => play('S_A'));
  assert.match(packets.filter(p => p.type === 'tutorial_feedback').at(-1).data.message, /마이티는 무늬를 따르지 않아도/);
  unchanged(() => play('S_2'));
  assert.match(packets.filter(p => p.type === 'tutorial_feedback').at(-1).data.message, /클로버/);
  play('C_2'); step('follow_result');
  assert.equal(room.lastTrickWinner.clientId, room.players[2].clientId);
  assert.equal(room.friendRevealed, false);
  assert.equal(state().tutorialHoldTable, true);
  next('trump');
  assert.equal(state().tableWinningCardId, 'D_K');
  ack(); play('H_4'); step('trump_compare');
  assert.equal(state().tableWinningCardId, 'H_4');
  assert.equal(room.tableCards.length, 4);
  assert.equal(room.trickComplete, false);
  next('trump_result');
  assert.equal(state().tableWinningCardId, 'H_6');
  assert.equal(room.currentTurnIndex, 1);
  next('special'); next('mighty');
  assert.equal(room.tableCards[0].card.id, 'C_K');
  assert.equal(state().friendClientId, null);
  ack(); play('S_A'); step('mighty_result');
  assert.equal(room.friendRevealed, true);
  assert.equal(room.lastTrickWinner.clientId, ws.clientId);
  for (const p of room.players) assert.equal(rooms.publicState(room, p.clientId).friendClientId, ws.clientId);
  const wonTrick = JSON.stringify(room.tableCards);
  unchanged(() => play('C_3'));
  next('points');
  assert.equal(JSON.stringify(room.tableCards), wonTrick);
  assert.equal(state().tutorialHoldTable, true);
  assert.equal(room.tableCards.length, 5);
  assert.equal(room.tableCards.reduce((n, e) => n + e.card.point, 0), 4);
  assert.equal(state().tutorialHoldTable, true);
  next('call');
  assert.equal(state().tutorialHoldTable, false);
  assert.equal(packets.filter(p => p.type === 'game_state' && p.data.tutorialCollect).at(-1).data.tableCards.length, 5);
  ack();
  unchanged(() => action('play_card', { cardId: 'C_3', activateJokerCall: false }));
  action('play_card', { cardId: 'C_3', activateJokerCall: true }); step('call_result');
  assert.equal(room.tableCards[3].card.id, 'JOKER');
  assert.equal(state().tableWinningCardId, 'C_10');
  assert.equal(room.trickHistory.length, 4);
  next('round_end'); next('roles'); next('roles_friend'); next('roles_citizens'); next('bid');
  assert.equal(new Set(deal()).size, 53);
  assert.ok(!room.players[0].hand.some(c => c.id === 'H_K' || c.id === 'S_A'));
  assert.ok(room.players[4].hand.some(c => c.id === 'S_A'));
  ack();
  unchanged(() => action('bid', { targetScore: 13, trumpSuit: 'SPADE' }));
  action('bid', { targetScore: 13, trumpSuit: 'HEART' }); step('bid_result');
  assert.equal(packets.filter(p => p.type === 'bid_result').length, 0, 'election animation must wait for the exchange acknowledgement');
  assert.equal(room.declarerClientId, ws.clientId);
  assert.equal(room.players[0].hand.length, 10);
  next('discard'); assert.equal(room.players[0].hand.length, 13); ack();
  assert.equal(packets.filter(p => p.type === 'bid_result').length, 1);
  unchanged(() => action('discard_kitty', { cardIds: ['S_2','S_2','C_2'] }));
  unchanged(() => action('discard_kitty', { cardIds: ['S_2','D_2','missing'] }));
  action('discard_kitty', { cardIds: ['S_2','D_2','C_2'] }); step('discard_result');
  assert.equal(room.players[0].hand.length, 10);
  next('friend'); ack();
  unchanged(() => action('choose_friend', { friendCardId: 'H_K' }));
  action('choose_friend', { friendCardId: 'S_A' }); step('friend_result');
  next('lead'); ack(); play('H_A'); step('lead_result');
  assert.equal(room.lastTrickWinner.clientId, ws.clientId);
  assert.equal(room.trickHistory.length, 1);
  assert.equal(room.friendRevealed, false);
  next('rescue'); ack(); play('H_Q'); step('rescue_threat');
  assert.equal(room.tableCards.length, 4);
  assert.equal(room.trickComplete, false);
  assert.equal(state().tableWinningCardId, 'H_K');
  assert.equal(state().friendClientId, null);
  assert.equal(state().declarerTeamScore, 1);
  unchanged(() => play('H_J'));
  next('reveal');
  assert.equal(room.tableCards[4].card.id, 'S_A');
  assert.equal(state().tableWinningCardId, 'S_A');
  assert.equal(state().friendClientId, room.players[4].clientId);
  assert.equal(room.lastTrickWinner.clientId, room.players[4].clientId);
  assert.equal(room.tableCards.reduce((sum, entry) => sum + entry.card.point, 0), 3);
  assert.equal(state().declarerTeamScore, 4);
  next('free');
  return { rooms, packets, tutorial, ws, room, ack, next, step, play, action, state, unchanged, deal, firstDeal };
}

// Vary both legal learner choices and bot replies, including bot wins/leads,
// mighty revelation and joker effects. No scripted answer is imposed in free play.
const originalRandom = Math.random;
let botLeads = 0;
let illegalAttempts = 0;
try {
  for (let seed = 1; seed <= 40; seed++) {
    let randomState = seed;
    Math.random = () => ((randomState = (Math.imul(randomState, 1664525) + 1013904223) >>> 0) / 2 ** 32);
    const s = session();
    for (let n = 0; n < 3; n++) {
      s.step('free');
      assert.equal(s.room.tutorial.view.cardIds.length, 0);
      if (!s.room.trickComplete && s.room.tableCards.length > 0) botLeads++;
      s.ack();
      const table = s.room.trickComplete ? [] : s.room.tableCards;
      const hand = s.room.players[0].hand;
      const legal = hand.filter(card => Rules.canPlayCard({ playerHand: hand, card, tableCards: table, ruleConfig: s.room.ruleConfig }));
      const illegal = hand.find(card => !legal.includes(card));
      if (illegal) { s.unchanged(() => s.play(illegal.id)); illegalAttempts++; }
      s.unchanged(() => s.play('not-in-hand'));
      const card = seed % 2 === 0 ? legal[0] : legal.at(-1);
      s.action('play_card', { cardId: card.id, declaredSuit: 'HEART', activateJokerCall: false });
      s.step('free_result');
      assert.equal(s.room.trickHistory.length, n + 3);
      assert.equal(s.room.tableCards.length, 5);
      assert.ok(s.room.players.every(p => p.hand.length === 7 - n));
      assert.equal(s.state().tutorialHoldTable, true);
      const revision = s.room.tutorial.revision;
      s.next(n === 2 ? 'complete' : 'free');
      s.unchanged(() => s.action('tutorial_ack', { revision }));
    }
    assert.equal(s.room.tutorial.freeTricks, 3);
    assert.equal(s.room.tutorial.view.complete, true);
    s.ack(); s.step('complete');
    s.action('tutorial_restart'); s.step('intro');
    assert.deepEqual(s.deal(), s.firstDeal);
    s.tutorial.sync(s.room);
    assert.equal(s.packets.at(-1).type, 'tutorial_state');
    s.action('leave_room');
    assert.equal(s.rooms.getRoom(s.room.roomId), undefined);
    assert.equal(s.ws.roomId, null);
  }
} finally { Math.random = originalRandom; }
assert.ok(botLeads > 0, 'exercise a bot leading a free trick');
assert.ok(illegalAttempts > 0, 'exercise illegal suit attempts in free play');
console.log('Tutorial: four teaching tricks, three free tricks across 40 seeds, rules, barriers, collection, restart and exit passed.');
